                    Column(
                        modifier = Modifier.padding(20.dp),
                        verticalArrangement = Arrangement.spacedBy(16.dp)
                    ) {
                        FeatureRow(
                            icon = Icons.Default.Cloud,
                            title = "Đồng bộ đám mây Firebase",
                            subtitle = "Lưu danh sách game yêu thích & cấu hình stream"
